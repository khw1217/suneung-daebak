# [기능 3] 절대평가 등급 계산
#   영어·한국사 점수를 넣으면 몇 등급인지 계산해 주는 함수(기계)예요.
# ═════════════════════════════════════════════

# def 함수이름(재료1, 재료2, 재료3):  → '이런 재료를 받는 기계를 만든다'는 뜻
#   - score    : 현재 점수   (예: 영어 82점)
#   - max_score: 그 과목 만점 (예: 100)
#   - step     : 등급 간격   (예: 10)
def absolute_grade(score, max_score, step):
    """영어: 90점 이상 1등급, 10점 간격 / 한국사: 40점 이상 1등급, 5점 간격"""
    # 1등급 기준 점수 = 만점 - 10
    #   영어: 100 - 10 = 90점 / 한국사: 50 - 10 = 40점
    cut1 = max_score - 10

    # 만약 점수가 1등급 기준 이상이면 → 바로 '1등급'이라고 돌려주고(return) 함수 끝
    if score >= cut1:
        return 1

    # 1등급이 아니면 아래 공식으로 등급을 계산해요.
    #   등급 = 1 + (1등급 기준 - 내 점수) ÷ 등급 간격  → 소수점은 올림(math.ceil)
    #   예) 영어 82점: 1 + (90 - 82) ÷ 10 = 1 + 0.8 → 올림하면 1 + 1 = 2등급
    #   예) 영어 60점: 1 + (90 - 60) ÷ 10 = 1 + 3   = 4등급
    #   min(9, ...)는 '아무리 낮아도 9등급까지만' 나오게 막는 장치예요.
    return min(9, 1 + math.ceil((cut1 - score) / step))


# ═════════════════════════════════════════════
# [기능 4] 목표 점수 검사에 쓰는 '목표 등급 최소 점수'
#   "이 등급을 받으려면 최소 몇 점이 필요한가?"를 계산하는 함수예요.
# ═════════════════════════════════════════════
def min_score_for_grade(grade, max_score, step):
    # 1등급 기준 점수 (영어 90점, 한국사 40점)
    cut1 = max_score - 10

    # 필요한 최소 점수 = 1등급 기준 - (원하는 등급 - 1) × 등급 간격
    #   예) 영어 2등급: 90 - (2 - 1) × 10 = 80점
    #   예) 한국사 3등급: 40 - (3 - 1) × 5 = 30점
    #   max(0, ...)는 계산 결과가 0점보다 작아지지 않게 막는 장치예요.
    return max(0, cut1 - (grade - 1) * step)


