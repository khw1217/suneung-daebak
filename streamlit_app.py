# [기능 7] 공부 방법 추천
#   목표까지 얼마나 남았는지(비율)에 따라 공부 방법을 골라 주는 함수예요.
#   gap_ratio = (목표 점수 - 현재 점수) ÷ 만점
#   예) 국어 만점 100, 현재 60, 목표 80 → (80 - 60) ÷ 100 = 0.2 (20%)
# ═════════════════════════════════════════════
def study_level(gap_ratio):
    # 남은 비율이 20%(0.2) 이상 → 많이 부족함 → 기초부터 다시
    if gap_ratio >= 0.2:
        return "개념 복습 → 쉬운 문제로 확인"
    # 위 조건이 아니고, 5%(0.05) 이상 → 조금 부족함 → 기출 문제로 실력 다지기
    if gap_ratio >= 0.05:
        return "기출 풀이 → 오답 정리"
    # 둘 다 아니면(5% 미만 또는 이미 목표 달성) → 실전 감각 유지
    return "시간 재고 실전 풀이 (감 유지)"


# ═════════════════════════════════════════════
# [기능 5] 공부 가능 시간 계산
#   시작~끝 시각을 받아서 '공부 칸' 목록을 만들어 주는 함수예요.
#   예) 18:30 ~ 22:30, 공부 50분 + 휴식 10분이면
#       → 총 240분 = (50+10)분 × 4묶음 → 공부 칸 [50, 50, 50, 50]
# ═════════════════════════════════════════════
def make_sessions(start, end, block, rest):
    """시작~끝 시각을 '공부 + 휴식' 묶음으로 나눠 공부 칸 목록을 만든다."""
    # 시각(18:30)만으로는 빼기 계산이 안 돼서, 아무 날짜(2000년 1월 1일)를 붙여
    # '날짜+시각' 형태로 바꿔요. 날짜 자체는 의미 없고 계산용이에요.
    t0 = datetime.combine(datetime(2000, 1, 1), start)   # 시작 시각
    t1 = datetime.combine(datetime(2000, 1, 1), end)     # 끝 시각

    # 만약 끝 시각이 시작 시각보다 같거나 이르면 (예: 22:00 시작 → 01:00 끝)
    # 자정을 넘긴 것으로 보고 끝 시각에 하루를 더해요. → 다음 날 01:00
    if t1 <= t0:
        t1 += timedelta(days=1)

    # 전체 시간(분) = (끝 - 시작)을 초 단위로 구한 뒤 60으로 나눔
    #   예) 18:30 ~ 22:30 → 14400초 ÷ 60 = 240분
    #   '//'는 나눈 뒤 소수점을 버리는 나눗셈이에요. (예: 7 // 2 = 3)
    total = int((t1 - t0).total_seconds() // 60)

    # '공부 + 휴식' 묶음이 몇 번 들어가는지 계산
    #   예) 240 // (50 + 10) = 4묶음
    full_sets = total // (block + rest)

    # 묶음을 다 넣고 남는 자투리 시간
    #   예) 240 - 4 × 60 = 0분
    leftover = total - full_sets * (block + rest)

    # 공부 칸 목록 만들기: [50] × 4 → [50, 50, 50, 50]
    sessions = [block] * full_sets

    # 자투리 시간이 20분(MIN_LAST) 이상이면 버리기 아까우니 공부 칸으로 하나 더 추가
    #   단, 한 번 공부 시간(block)보다 길게는 안 넣어요 → min(block, leftover)
    #   예) 자투리 30분 → [50, 50, 50, 50, 30]
    if leftover >= MIN_LAST:
        sessions.append(min(block, leftover))

    # 결과 두 개를 돌려줘요: 시작 시각, 공부 칸 목록
    return t0, sessions


# ═════════════════════════════════════════════
# [기능 6] 공부 시간 배분
#   "목표까지 많이 남은 과목에 시간을 더 준다"를 실제로 계산하는 함수예요.
#   rows: 과목별 정보 목록 / study_minutes: 실제 공부할 수 있는 총 시간(분)
# ═════════════════════════════════════════════
def allocate_minutes(rows, study_minutes):
    """목표까지 남은 점수가 큰 과목일수록 시간을 더 배정한다(10분 단위)."""

    # ① 과목당 최소 시간 정하기
    #    원래는 20분인데, 전체 시간이 짧으면 모든 과목이 들어갈 수 있게 줄여요.
    #    (총 시간 ÷ 과목 수)를 10분 단위로 내린 값과 20분 중 작은 값, 단 최소 10분
    #    예) 총 200분, 6과목 → 200 ÷ 6 = 33 → 10분 단위로 30 → min(20, 30) = 20분
    #    예) 총  60분, 6과목 →  60 ÷ 6 = 10 → min(20, 10) = 10분
    min_each = max(UNIT, min(MIN_EACH, (study_minutes // len(rows)) // UNIT * UNIT))

    # ② 과목마다 '비중'(얼마나 시간을 줄지의 무게) 계산
    #    for r in rows: → 과목을 하나씩 꺼내서 r이라고 부르며 아래 작업을 반복
    for r in rows:
        # 남은 점수 = 목표 - 현재. 이미 목표를 넘었으면 음수 대신 0
        #   예) 목표 80, 현재 60 → 20점 / 목표 80, 현재 90 → 0점
        r["gap"] = max(0, r["target"] - r["score"])
        # 남은 점수 비율 = 남은 점수 ÷ 만점 (만점이 다른 과목끼리 공평하게 비교하려고)
        #   예) 국어 20 ÷ 100 = 0.2 / 통합사회 10 ÷ 50 = 0.2 → 똑같이 부족한 것으로 봄
        r["gap_ratio"] = r["gap"] / r["max"]
        # 비중 = 0.15 + 남은 비율
        #   0.15는 '기본 점수'예요. 이미 목표를 넘은 과목도 감 유지용으로 조금은 시간을 받게 함
        r["weight"] = 0.15 + r["gap_ratio"]   # 목표를 넘은 과목도 감 유지용 비중 0.15

    # ③ 모든 과목의 비중을 더한 합계
    total_w = sum(r["weight"] for r in rows)

    # ④ 비중에 비례해서 시간 나누기
    for r in rows:
        # 정확한 몫 = 총 시간 × (내 비중 ÷ 비중 합계)   예) 200 × (0.35 ÷ 1.6) = 43.75분
        r["raw"] = study_minutes * r["weight"] / total_w
        # 10분 단위로 내림 (43.75 → 40분). 단, 최소 시간보다 적으면 최소 시간으로
        r["minutes"] = max(min_each, int(r["raw"] // UNIT) * UNIT)

    # ⑤ 내림 때문에 생긴 차이 맞추기
    #    diff = 총 시간 - 지금까지 나눠 준 시간의 합
    #    (양수면 시간이 남은 것, 음수면 너무 많이 나눠 준 것)
    diff = study_minutes - sum(r["minutes"] for r in rows)

    # 시간이 10분 이상 남아 있는 동안 반복:
    #   내림으로 가장 많이 손해 본 과목(정확한 몫 - 받은 시간이 가장 큰 과목)에 10분 추가
    while diff >= UNIT:   # 남는 시간 → 내림으로 많이 잘린 과목부터 +10분
        r = max(rows, key=lambda x: x["raw"] - x["minutes"])
        r["minutes"] += UNIT    # 그 과목에 10분 더하고
        diff -= UNIT            # 남은 시간에서 10분 빼기

    # 시간을 너무 많이 나눠 준 동안 반복 (최소 시간 보장 때문에 생길 수 있음):
    #   최소 시간보다 여유 있게 받은 과목 중, 정확한 몫보다 가장 많이 받은 과목에서 10분 빼기
    while diff < 0:       # 넘치는 시간 → 많이 받은 과목부터 -10분
        r = max((x for x in rows if x["minutes"] - UNIT >= min_each),
                key=lambda x: x["minutes"] - x["raw"], default=None)
        # 더 뺄 수 있는 과목이 없으면(r이 None = 아무것도 없음) 반복을 멈춤(break)
        if r is None:
            break
        r["minutes"] -= UNIT    # 그 과목에서 10분 빼고
        diff += UNIT            # 넘친 시간 10분 줄이기

    # ⑥ 비중이 큰 과목(= 더 부족한 과목)이 앞에 오도록 정렬
    #    reverse=True → 큰 것부터 작은 것 순서(내림차순)
    rows.sort(key=lambda r: r["weight"], reverse=True)   # 부족한 과목이 앞으로

    # ⑦ 10분이 안 되는 자투리 시간(예: 5분)이 남았으면 가장 부족한 과목(맨 앞)에 줌
    if diff > 0:          # 10분이 안 되는 자투리는 가장 부족한 과목에
        rows[0]["minutes"] += diff

    # 과목별 배정 시간이 적힌 목록을 돌려줌
    return rows


# ═════════════════════════════════════════════
# [기능 8] 시간표 생성
#   배정된 과목별 시간을 '공부 칸'에 순서대로 채워서 실제 시간표를 만들어요.
#   비유: 공부 칸 = 상자, 과목 시간 = 물건. 앞 과목부터 상자에 꽉꽉 채워 넣고,
#         상자 사이사이에 '휴식'을 끼워 넣는 방식이에요.
#   rows: 과목 목록 / t: 시작 시각 / sessions: 공부 칸 목록 / rest: 휴식 시간
# ═════════════════════════════════════════════
def build_schedule(rows, t, sessions, rest):
    # 대기열(queue) 만들기: [과목 이름, 남은 공부 시간, 할 일]을 과목 순서대로 줄 세움
    #   예) [["수학", 40, "..."], ["영어", 40, "..."], ...]
    queue = [[r["name"], r["minutes"], r["plan"]] for r in rows]

    # 완성된 시간표의 줄들을 모아 둘 빈 목록
    schedule = []

    # 공부 칸을 하나씩 꺼내면서 반복
    #   i = 몇 번째 칸인지(0부터 시작), length = 그 칸의 길이(분)
    for i, length in enumerate(sessions):
        # 이 칸에 아직 채울 수 있는 시간
        remain = length

        # 칸에 남은 시간이 있고, 대기 중인 과목도 있는 동안 반복
        while remain > 0 and queue:
            # 대기열 맨 앞 과목의 정보 꺼내 보기
            name, mins, plan = queue[0]
            # 이번에 쓸 시간 = '과목의 남은 시간'과 '칸의 남은 시간' 중 작은 것
            #   예) 수학 40분 남음, 칸 50분 남음 → 40분 사용
            use = min(mins, remain)
            # 시간표에 한 줄 추가: 시작 시각, 끝 시각, 과목, 할 일
            #   strftime("%H:%M") → 시각을 "18:30" 같은 글자로 바꿔 줌
            schedule.append({
                "시작": t.strftime("%H:%M"),
                "끝": (t + timedelta(minutes=use)).strftime("%H:%M"),
                "과목": name,
                "할 일": plan,
            })
            t += timedelta(minutes=use)   # 현재 시각을 사용한 만큼 뒤로 이동
            remain -= use                 # 칸의 남은 시간 줄이기
            queue[0][1] -= use            # 그 과목의 남은 공부 시간 줄이기
            # 그 과목 시간을 다 썼으면 대기열에서 빼고(pop) 다음 과목으로 넘어감
            if queue[0][1] <= 0:
                queue.pop(0)

        # 칸 하나를 다 채운 뒤:
        #   마지막 칸이 아니고, 아직 남은 과목이 있으면 → 휴식 줄 추가
        if i < len(sessions) - 1 and queue:
            schedule.append({
                "시작": t.strftime("%H:%M"),
                "끝": (t + timedelta(minutes=rest)).strftime("%H:%M"),
                "과목": "☕ 휴식",
                "할 일": "스트레칭, 물 마시기",
            })
            t += timedelta(minutes=rest)  # 휴식 시간만큼 현재 시각 이동

    # 모은 줄들을 pandas 표(DataFrame)로 바꿔서 돌려줌 → 화면에 표로 보여 줄 수 있음
    return pd.DataFrame(schedule)


